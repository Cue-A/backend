-- 이미 적용된 마이그레이션 파일은 고치지 마세요. 체크섬이 달라져 앱이 시작하지 않습니다.
-- 스키마를 바꿀 때는 다음 번호로 새 파일을 추가합니다. docs/02-database.md 참고.

create table answer (
    answer_end float(53),
    answer_start float(53),
    score integer,
    think_time float(53),
    answer_id bigint generated by default as identity,
    answered_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    question_id varchar(50) not null,
    session_id varchar(50) not null,
    answer_text text,
    metrics jsonb,
    primary key (answer_id),
    constraint uk_answer_question unique (session_id, question_id)
);

create table badge (
    badge_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    category varchar(20) not null,
    status varchar(20) not null,
    condition_type varchar(30) not null,
    badge_code varchar(50) not null unique,
    badge_name varchar(50) not null,
    icon_url varchar(500),
    description varchar(255) not null,
    condition_data jsonb not null,
    primary key (badge_id)
);

create table bookmarked_question (
    bookmarked_question_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    question_id varchar(50) not null,
    session_id varchar(50) not null,
    user_id varchar(50) not null,
    memo varchar(500),
    primary key (bookmarked_question_id),
    constraint uk_bookmarked_question unique (user_id, session_id, question_id)
);

create table calendar_event (
    calendar_event_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    scheduled_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    interview_method varchar(10) not null check (interview_method in ('ONLINE','OFFLINE')),
    interview_round varchar(30),
    job_role varchar(50) not null,
    user_id varchar(50) not null,
    company_name varchar(100) not null,
    location varchar(200),
    meeting_url varchar(500),
    memo text,
    primary key (calendar_event_id)
);

create table company (
    updated_at date not null,
    verified boolean not null,
    company_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    values_format varchar(20) not null check (values_format in ('WORD','PRINCIPLE','MIXED')),
    company_name varchar(100) not null unique,
    industry varchar(100) not null,
    interview_style varchar(200),
    talent_profile text,
    core_values jsonb not null,
    job_requirements jsonb,
    source_url text[] not null,
    primary key (company_id)
);

create table document (
    created_at timestamp(6) with time zone not null,
    deleted_at timestamp(6) with time zone,
    doc_id bigint generated by default as identity,
    file_size bigint,
    updated_at timestamp(6) with time zone not null,
    file_format varchar(10) check (file_format in ('PDF','DOCX','TXT')),
    source_type varchar(10) not null check (source_type in ('FILE','MARKDOWN')),
    public_id uuid not null unique,
    doc_type varchar(20) not null check (doc_type in ('RESUME','PORTFOLIO')),
    status varchar(20) not null check (status in ('UPLOADED','PARSING','READY','FAILED')),
    user_id varchar(50) not null,
    doc_title varchar(100) not null,
    mime_type varchar(100),
    doc_text text,
    file_name varchar(255),
    object_key text,
    primary key (doc_id)
);

create table folder (
    created_at timestamp(6) with time zone not null,
    folder_id bigint generated by default as identity,
    public_id uuid not null unique,
    folder_name varchar(50) not null,
    user_id varchar(50) not null,
    primary key (folder_id)
);

create table goal (
    end_date date not null,
    start_date date not null,
    target_value integer not null,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    goal_id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    goal_type varchar(20) not null,
    status varchar(20) not null,
    target_metric varchar(30) not null,
    user_id varchar(50) not null,
    primary key (goal_id)
);

create table notification_setting (
    badge_enabled boolean not null,
    calendar_enabled boolean not null,
    goal_enabled boolean not null,
    marketing_enabled boolean not null,
    report_enabled boolean not null,
    streak_enabled boolean not null,
    created_at timestamp(6) with time zone not null,
    notification_setting_id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    user_id varchar(50) not null unique,
    primary key (notification_setting_id)
);

create table question (
    answer_is_timeout boolean not null,
    is_bookmarked boolean not null,
    is_replay boolean not null,
    is_spare_topic boolean not null,
    question_number integer not null,
    topic_index integer not null,
    difficulty varchar(5),
    created_at timestamp(6) with time zone not null,
    category varchar(20),
    type varchar(20) not null check (type in ('QUESTION','FOLLOWUP','REASK')),
    question_id varchar(50) not null,
    reask_of varchar(50),
    session_id varchar(50) not null,
    answer_audio_object_key text,
    answer_video_object_key text,
    audio_url text,
    text text not null,
    primary key (question_id, session_id)
);

create table report (
    attempt integer not null,
    score_content integer,
    score_gaze integer,
    score_speech integer,
    score_total integer,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    report_id bigint generated by default as identity,
    public_id uuid not null unique,
    retry_status varchar(20) check (retry_status in ('PROCESSING','FAILED')),
    status varchar(20) not null check (status in ('PROCESSING','COMPLETED','PARTIAL','FAILED')),
    error_code varchar(50),
    session_id varchar(50) not null unique,
    ai_task_id varchar(100),
    report_data jsonb,
    primary key (report_id)
);

create table session (
    duration_limit integer,
    hide_question_text boolean not null,
    question_count integer not null,
    company_id bigint,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    document_id bigint not null,
    folder_id bigint,
    updated_at timestamp(6) with time zone not null,
    mode varchar(20) not null,
    persona varchar(20) not null check (persona in ('FRIENDLY','PRESSURE')),
    status varchar(20) not null check (status in ('IN_PROGRESS','COMPLETED','ABORTED')),
    retry_of_session_id varchar(50),
    session_id varchar(50) not null,
    user_id varchar(50) not null,
    job_role varchar(100) not null,
    custom_talent text,
    primary key (session_id)
);

create table streak (
    activity_date date not null,
    answer_count integer not null,
    created_at timestamp(6) with time zone not null,
    streak_id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    user_id varchar(50) not null,
    primary key (streak_id),
    constraint uk_streak_user_date unique (user_id, activity_date),
    constraint ck_streak_answer_count check (answer_count >= 1)
);

create table user_auth (
    created_at timestamp(6) not null,
    provider varchar(20) not null check (provider in ('LOCAL','KAKAO')),
    auth_id varchar(50) not null,
    user_id varchar(50) not null,
    provider_id varchar(100),
    password varchar(255),
    primary key (auth_id),
    constraint uk_user_auth_provider unique (provider, provider_id),
    constraint uk_user_auth_user_provider unique (user_id, provider)
);

create table user_badge (
    badge_id bigint not null,
    earned_at timestamp(6) with time zone not null,
    user_badge_id bigint generated by default as identity,
    source_session_id varchar(50),
    user_id varchar(50) not null,
    primary key (user_badge_id),
    constraint uk_user_badge unique (user_id, badge_id)
);

create table user_company_interest (
    company_id bigint not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    user_id varchar(50) not null,
    primary key (id),
    constraint uk_user_company_interest unique (user_id, company_id)
);

create table user_profile (
    graduation_year integer,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    user_profile_id bigint generated by default as identity,
    career_level varchar(20),
    target_job_role varchar(50),
    user_id varchar(50) not null unique,
    major varchar(100),
    school_name varchar(100),
    introduction varchar(500),
    profile_image_url varchar(500),
    primary key (user_profile_id)
);

create table users (
    created_at timestamp(6) not null,
    nickname varchar(50) not null,
    user_id varchar(50) not null,
    email varchar(255) unique,
    primary key (user_id)
);

