-- 질문은행 「공통 질문」 탭 (Issue #136).
--
-- common_question      모두가 보는 기본 질문(user_id 가 null)과 사용자가 직접 추가한 내 질문(user_id 가 주인)을
--                      한 테이블에 둡니다. 밖으로는 public_id 만 내보냅니다.
-- common_question_note 사용자 × 질문 한 줄에 즐겨찾기 · 메모. 기본 질문은 모두가 같이 보고 즐겨찾기 · 메모는
--                      각자의 것이라 질문과 나눴습니다.
--
-- 면접 질문 북마크(bookmarked_question)는 세션 질문에 FK 로 묶여 있어 세션이 없는 질문을 담을 수 없어 따로 둡니다.
-- V3 · V4 는 열린 PR(#133 일정, #134 배지)이 먼저 쓰고 있어 V5 입니다.

create table common_question (
    common_question_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    public_id uuid not null unique,
    category varchar(10) not null check (category in ('인성','경험','지원동기','직무','기타')),
    user_id varchar(50),
    text varchar(200) not null,
    primary key (common_question_id)
);

create table common_question_note (
    favorite boolean not null,
    common_question_id bigint not null,
    common_question_note_id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    favorited_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone not null,
    user_id varchar(50) not null,
    memo varchar(500),
    primary key (common_question_note_id),
    constraint uk_common_question_note unique (user_id, common_question_id)
);

create index idx_common_question_user
   on common_question (user_id, created_at);

-- 내 질문을 지울 때 cascade 가 노트를 질문으로 찾습니다. 내 노트 조회는 uk_common_question_note 가 맡습니다.
create index idx_common_question_note_question
   on common_question_note (common_question_id);

alter table if exists common_question
   add constraint fk_common_question_user_id
   foreign key (user_id)
   references users
   on delete cascade;

alter table if exists common_question_note
   add constraint fk_common_question_note_common_question_id
   foreign key (common_question_id)
   references common_question
   on delete cascade;

alter table if exists common_question_note
   add constraint fk_common_question_note_user_id
   foreign key (user_id)
   references users
   on delete cascade;

